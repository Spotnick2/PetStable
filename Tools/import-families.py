"""Build the shipped family facts from the client's own CreatureFamily table.

Usage: python Tools/import-families.py ../References/Forever/db/forever-creaturefamily-1.60.1.70532.csv [--check]
The table is datamined client data (wago.tools), not an in-game observation. Only hunter pet
families are kept: the pet skill line is 270 and the family has a food mask. The mask is stored
as the client gives it; the names of its bits live in GuideData.lua so they can be corrected in one
place if a live check (C_StableInfo.GetStablePetFoodTypes) ever disagrees.
"""
import argparse
import csv
import hashlib
import io
import re
from pathlib import Path

PET_SKILL_LINE = 270
FIELDS = 'PetFoodMask,MinScale,MaxScale'


def table_build(path):
    match = re.search(r'-(\d+\.\d+\.\d+\.\d+)\.csv$', str(path))
    if not match:
        raise ValueError('Table name must end in -<version>.<build>.csv: ' + str(path))
    return match.group(1)


def families(raw):
    rows = list(csv.DictReader(io.StringIO(raw.decode('utf-8'))))
    if rows and any(field not in rows[0] for field in ['ID', 'Name_lang', 'PetFoodMask', 'MinScale', 'MaxScale', 'SkillLine_1']):
        raise ValueError('CreatureFamily table lacks expected columns')
    kept = {}
    for row in rows:
        mask = int(row['PetFoodMask'])
        if int(row['SkillLine_1']) != PET_SKILL_LINE or mask <= 0:
            continue
        family = int(row['ID'])
        if family in kept:
            raise ValueError('Duplicate family ID %d' % family)
        kept[family] = dict(name=row['Name_lang'], foodMask=mask, minScale=round(float(row['MinScale']), 3),
                            maxScale=round(float(row['MaxScale']), 3))
    return kept


def generate(raw, build):
    kept = families(raw)
    lines = ['-- Generated by Tools/import-families.py; do not hand edit.',
             '-- Datamined client table CreatureFamily: family facts, never availability or tameability.',
             'local _, NS = ...', 'local data=NS.CatalogData',
             'data.familyTraits={build=%s,fields=%s,revision=%s,' % (
                 q(build), q(FIELDS), q(hashlib.sha256(raw).hexdigest())),
             '    url=%s,' % q('https://wago.tools/db2/CreatureFamily?build=' + build),
             '    families={']
    for family in sorted(kept):
        row = kept[family]
        lines.append('        [%d]={name=%s,foodMask=%d,minScale=%s,maxScale=%s},' % (
            family, q(row['name']), row['foodMask'], num(row['minScale']), num(row['maxScale'])))
    lines.extend(['    }}', ''])
    return '\n'.join(lines)


def q(text):
    return '"' + text.replace('\\', '\\\\').replace('"', '\\"') + '"'


def num(value):
    return ('%g' % value)


if __name__ == '__main__':
    parser = argparse.ArgumentParser()
    parser.add_argument('table', type=Path)
    parser.add_argument('--check', action='store_true')
    args = parser.parse_args()
    output = Path(__file__).resolve().parent.parent / 'CatalogFamilies.lua'
    result = generate(args.table.read_bytes(), table_build(args.table))
    if args.check:
        if output.read_text(encoding='utf-8') != result:
            raise SystemExit('Generated family facts differ')
    else:
        output.write_text(result, encoding='utf-8', newline='\n')
    print('Family facts reproducible' if args.check else 'Generated ' + str(output))
